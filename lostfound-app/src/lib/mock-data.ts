const day = (n: number) => {
  const d = new Date();
  d.setDate(d.getDate() - n);
  return localYmd(d);
};
const at = (n: number, h: number) => {
  const d = new Date();
  d.setDate(d.getDate() - n);
  d.setHours(h, 10, 0, 0);
  return d.toISOString();
};

